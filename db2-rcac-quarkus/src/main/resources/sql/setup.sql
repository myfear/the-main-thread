CREATE ROLE RCAC_READ;
CREATE ROLE RCAC_PII;

CREATE PERMISSION LABSEC.TENANT_ROWS ON APP.CUSTOMERS C
    FOR ROWS WHERE EXISTS (
        SELECT 1 FROM LABSEC.TENANT_PRINCIPALS P
        WHERE P.AUTHID = SESSION_USER AND P.TENANT_ID = C.TENANT_ID
    )
    ENFORCED FOR ALL ACCESS ENABLE;

CREATE MASK LABSEC.EMAIL_MASK ON APP.CUSTOMERS
    FOR COLUMN EMAIL RETURN CASE
        WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'RCAC_PII') = 1 THEN EMAIL
        ELSE CAST(NULL AS VARCHAR(120))
    END ENABLE AT READ;

CREATE MASK LABSEC.CREDIT_MASK ON APP.CUSTOMERS
    FOR COLUMN CREDIT_LIMIT RETURN CASE
        WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'RCAC_PII') = 1 THEN CREDIT_LIMIT
        ELSE CAST(NULL AS DECIMAL(12,2))
    END ENABLE AT READ;

ALTER TABLE APP.CUSTOMERS ACTIVATE ROW ACCESS CONTROL;
ALTER TABLE APP.CUSTOMERS ACTIVATE COLUMN ACCESS CONTROL;

-- Grant data access only after both controls are active.
GRANT CONNECT ON DATABASE TO ROLE RCAC_READ;
GRANT SELECT ON TABLE APP.CUSTOMERS TO ROLE RCAC_READ;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_APPLICATION_HANDLE() TO ROLE RCAC_READ;
GRANT ROLE RCAC_READ TO USER TENA, USER TENB, USER TENAPII, USER TENNONE;
GRANT ROLE RCAC_PII TO USER TENAPII;

