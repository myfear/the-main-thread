-- A deliberately weaker mask on an isolated fictional fixture illustrates
-- inference under the default AT RESULT semantic. It is not used by the API.
CREATE TABLE APP.MASK_RESULT_EXAMPLE (CREDIT_LIMIT DECIMAL(12,2));
INSERT INTO APP.MASK_RESULT_EXAMPLE VALUES (12000.00);
CREATE MASK LABSEC.RESULT_EXAMPLE_MASK ON APP.MASK_RESULT_EXAMPLE
    FOR COLUMN CREDIT_LIMIT RETURN CASE
        WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'RCAC_PII') = 1 THEN CREDIT_LIMIT
        ELSE CAST(NULL AS DECIMAL(12,2))
    END ENABLE;
ALTER TABLE APP.MASK_RESULT_EXAMPLE ACTIVATE COLUMN ACCESS CONTROL;
GRANT SELECT ON TABLE APP.MASK_RESULT_EXAMPLE TO USER TENA;
